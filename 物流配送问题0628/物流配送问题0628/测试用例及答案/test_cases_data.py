#       depot→c3 = 5.0（√(3²+4²)）
#       c3→c4 = 0.0（坐标相同）
#       c4→depot = 5.0
#       V1 合计 = 10.0
#   V2: c1+c2+c5（重量 1+1+1=3），路线 depot→c1→c2→c5→depot
#       depot→c1 = 0.0（与 depot 重合）
#       c1→c2 = 0.0（坐标相同）
#       c2→c5 = 1.0
#       c5→depot = 1.0
#       V2 合计 = 2.0
#   总距离 = 10.0 + 2.0 = 12.0
#
# 考核重点：
#   1. c1/c2 在 depot（距离 0），是否被跳过？→ 必须包含
#   2. c3/c4 在同一位置且重量合计恰好等于容量，是否放在同一辆车？→ 应该同车
#   3. 如果 c3/c4 被拆到不同车辆：
#      V1: depot→c1→c2→c3→depot = 0+0+5+5 = 10.0
#      V2: depot→c4→c5→depot = 5+4.243+1 = 10.243
#      总距离 ≈ 20.243（浪费约 8.24）
#
# 验收标准：
#   - num_vehicles == 2（总重量 8 > 容量 5）
#   - 所有 5 个坐标都出现在 routes 中
#   - c3 和 c4 在同一辆车中
#   - total_distance == 12.0


